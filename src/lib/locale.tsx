const localeContext = createContext<LocaleState>({
  locale: "en",
  setLocale: () => undefined
});

function readStoredLocale(): Locale {
  try {
    const stored = localStorage.getItem(LOCALE_STORAGE_KEY);
    return stored === "zh-CN" || stored === "en" ? stored : "en";
  } catch {
    return "en";
  }
}

function writeStoredLocale(locale: Locale) {
  try {
    localStorage.setItem(LOCALE_STORAGE_KEY, locale);
  } catch {
    // Local storage may be unavailable in restricted environments.
  }
}

function applyValues(template: string, values?: Record<string, string | number>) {
  if (!values) return template;
  return template.replace(/\{([^}]+)\}/g, (match, name: string) => {
    const value = values[name];
    return value === undefined ? match : String(value);
  });
}

export function t(locale: Locale, key: MessageKey, values?: Record<string, string | number>): string {
  const catalog = messages[locale][key];
  if (typeof catalog === "function") {
    return catalog(values ?? {});
  }
  if (typeof catalog === "string") {
    return applyValues(catalog, values);
  }
  return String(key);
}

export function useLocale(): LocaleState {
  return useContext(localeContext);
}

export function useT(): Translate {
  const { locale } = useLocale();
  return (key, values) => t(locale, key, values);
}

export function LocaleProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(readStoredLocale());

  useEffect(() => {
    writeStoredLocale(locale);
  }, [locale]);

  const setLocale = (next: Locale) => {
    setLocaleState(next);
  };

  const value = useMemo(() => ({ locale, setLocale }), [locale]);

  return <localeContext.Provider value={value}>{children}</localeContext.Provider>;
}
